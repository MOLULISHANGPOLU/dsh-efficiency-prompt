export const inject = ["systemPrompt"];

export function apply(ctx) {
  ctx.systemPrompt.section({
    name: "dsh-efficiency-prompt",
    order: 4800,
    interpolate: false,
    text: () => PROMPT + COLLABORATION,
  });
}

const plugin = { name: "dsh-efficiency-prompt", inject, apply };
export default plugin;
